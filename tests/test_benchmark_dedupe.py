from __future__ import annotations

from pathlib import Path

import pytest
from pydantic import BaseModel, ValidationError

from mojilex_cli.benchmark import (
    MANDATORY_DEDUPE_STRATA,
    DeclaredFile,
    DedupeBenchmarkCase,
    DedupeBenchmarkManifest,
    DedupeEvidence,
    DedupeObservation,
    RightsRecord,
    RuntimeComponent,
    dedupe_benchmark_split_sha256,
    evaluate_dedupe_benchmark,
)
from mojilex_cli.benchmark.common import BenchmarkError, declared_files_sha256, load_manifest
from mojilex_cli.benchmark.dedupe import _exact_memberships, _same_group


def _case(index: int, *, split: str | None = None) -> DedupeBenchmarkCase:
    labels = (
        "binary-exact",
        "decoded-exact",
        "canonical-render-match",
        "same-artwork",
        "variant",
        "not-duplicate",
    )
    label = labels[index % len(labels)]
    return DedupeBenchmarkCase(
        case_id=f"case-{index:04d}",
        split=split or ("development" if index < 250 else "holdout"),
        left_emoji_id=f"mxe_{index:04d}a",
        right_emoji_id=f"mxe_{index:04d}b",
        rights_id="synthetic",
        strata=MANDATORY_DEDUPE_STRATA,
        isolation_groups=(f"artwork-{index:04d}",),
        pair_label=label,
        binary_exact_expected=label == "binary-exact",
        decoded_exact_expected=label in {"binary-exact", "decoded-exact"},
        near_candidate_expected=label != "not-duplicate",
    )


def _manifest(cases: tuple[DedupeBenchmarkCase, ...]) -> DedupeBenchmarkManifest:
    files = (DeclaredFile(path="dataset.json", sha256="a" * 64),)
    return DedupeBenchmarkManifest(
        manifest_type="mojilex-dedupe-benchmark-v1",
        schema_version="1.0.0",
        benchmark_id="dedupe-golden-v1",
        benchmark_version="1.0.0",
        dedupe_profile="dedupe-v1",
        dedupe_profile_sha256="b" * 64,
        dataset_path="fixture",
        dataset_sha256=declared_files_sha256(files),
        split_sha256=dedupe_benchmark_split_sha256(cases),
        dataset_files=files,
        cli_commit="c" * 40,
        decoder_backend_fingerprint="d" * 64,
        runtime_components=(RuntimeComponent(component_id="python", version="3.11.9"),),
        exact_command="mojilex benchmark-dedupe --manifest <PATH>",
        rights=(
            RightsRecord(
                rights_id="synthetic",
                basis="synthetic",
                license_spdx="CC0-1.0",
                attribution="Generated by the MojiLex benchmark test suite.",
                redistribution_allowed=True,
            ),
        ),
        cases=cases,
        maximum_comparisons=1_000,
    )


def _evidence(cases: tuple[DedupeBenchmarkCase, ...]) -> DedupeEvidence:
    return DedupeEvidence(
        observations=tuple(
            DedupeObservation(
                case_id=case.case_id,
                binary_exact_observed=case.binary_exact_expected,
                decoded_exact_observed=case.decoded_exact_expected,
                near_candidate_observed=case.near_candidate_expected,
            )
            for case in cases
        ),
        comparisons=len(cases),
        indexed_items=2_000,
        suppressed_bucket_count=2,
        candidate_overflow_count=3,
        candidate_count_before_limit_total=999,
    )


def test_dedupe_golden_report_passes_and_is_deterministic() -> None:
    cases = tuple(_case(index) for index in range(500))
    manifest = _manifest(cases)
    evidence = _evidence(cases)

    first = evaluate_dedupe_benchmark(manifest, evidence, manifest_sha256="e" * 64)
    second = evaluate_dedupe_benchmark(manifest, evidence, manifest_sha256="e" * 64)

    assert first == second
    assert first["passed"] is True
    assert first["metrics"]["near"]["precision_bp"] == 10_000
    assert first["candidate_overflow_count"] == 3
    assert first["pair_label_counts"]["not-duplicate"] > 0
    assert len(first["report_sha256"]) == 64


def test_dedupe_report_fails_closed_on_all_pairs_or_missing_observation() -> None:
    cases = tuple(_case(index) for index in range(500))
    manifest = _manifest(cases)
    evidence = _evidence(cases)
    all_pairs = DedupeEvidence(
        observations=evidence.observations,
        comparisons=1,
        indexed_items=2,
        suppressed_bucket_count=0,
    )
    report = evaluate_dedupe_benchmark(manifest, all_pairs, manifest_sha256="e" * 64)
    assert report["gates"]["not_all_pairs"] is False
    assert report["passed"] is False

    with pytest.raises(BenchmarkError, match="cover every case"):
        evaluate_dedupe_benchmark(
            manifest,
            DedupeEvidence(
                observations=evidence.observations[:-1],
                comparisons=1,
                indexed_items=2,
                suppressed_bucket_count=0,
            ),
            manifest_sha256="e" * 64,
        )


def test_dedupe_manifest_rejects_cross_split_artwork_group() -> None:
    left = _case(0, split="development")
    right = _case(1, split="holdout").model_copy(update={"isolation_groups": left.isolation_groups})
    cases = (left, right)
    with pytest.raises(ValidationError, match="crosses benchmark split"):
        _manifest(cases)


def test_exact_membership_never_expands_group_pairs() -> None:
    members = [f"mxe_{index:05d}" for index in range(10_000)]
    binary, decoded = _exact_memberships(
        (
            {
                "id": "mxdg_binary",
                "scope": "entity",
                "group_type": "binary-exact",
                "members": members,
            },
            {
                "id": "mxdg_decoded",
                "scope": "entity",
                "group_type": "decoded-exact",
                "members": members[:2],
            },
        )
    )
    assert len(binary) == 10_000
    assert sum(len(value) for value in binary.values()) == 10_000
    assert _same_group(binary, members[0], members[-1]) is True
    assert _same_group(decoded, members[0], members[-1]) is False


def test_rights_and_counters_are_strict() -> None:
    with pytest.raises(ValidationError, match="credential-free HTTPS"):
        RightsRecord(
            rights_id="bad",
            basis="rights-cleared",
            license_spdx="MIT",
            attribution="Example",
            redistribution_allowed=True,
            source_url="https://user:secret@example.test/license",
        )

    cases = tuple(_case(index) for index in range(500))
    with pytest.raises(BenchmarkError, match="non-negative"):
        evaluate_dedupe_benchmark(
            _manifest(cases),
            DedupeEvidence(
                observations=_evidence(cases).observations,
                comparisons=-1,
                indexed_items=2_000,
                suppressed_bucket_count=0,
            ),
            manifest_sha256="f" * 64,
        )


def test_manifest_loader_rejects_duplicate_keys_and_type_coercion(tmp_path: Path) -> None:
    class TinyManifest(BaseModel):
        value: int

    duplicate = tmp_path / "duplicate.json"
    duplicate.write_text('{"value":1,"value":2}', encoding="utf-8")
    with pytest.raises(BenchmarkError, match="malformed, or invalid"):
        load_manifest(duplicate, TinyManifest)

    coerced = tmp_path / "coerced.json"
    coerced.write_text('{"value":"2"}', encoding="utf-8")
    with pytest.raises(BenchmarkError, match="malformed, or invalid"):
        load_manifest(coerced, TinyManifest)
